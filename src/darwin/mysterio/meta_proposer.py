def _ensure_overrides(darwin: Any) -> dict[str, Any]:
    overrides = getattr(darwin, "_planner_overrides", None)
    if overrides is None:
        overrides = {}
        setattr(darwin, "_planner_overrides", overrides)
    return overrides
