"""Generative proposal engine.

Synthesizes `ProposedModification` instances across multiple `MutationKind`
levels by reading Darwin's own causal model, self-model, world-model
hypotheses, and runtime telemetry. Strategies are registered in a plug-in
registry that the v9 `LiveResearcher` extends dynamically.

The strategies that ship in v6 are intentionally diverse so the
substrate exercises every `MutationKind` level from day one:

  - variable_driven   → RULE proposals (new precondition variables)
  - hypothesis_driven → RULE proposals (hidden-factor probes)
  - loop_starvation   → KERNEL proposals (interval adjustments)
  - consolidation     → RULE proposals (concept-pruning strategies)
  - gate_evolution    → GATE proposals (alternative accept-gate fns)

`SUBSYSTEM` and `MODULE` kinds are reserved for v6.5 (the code-gen layer)
and are not generated by the v6 strategies even though the grammar
supports them.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass
from typing import Any, Callable, Protocol

from darwin.mysterio.meta_gate import GateSpec, default_gate_fn, make_gate_spec
from darwin.mysterio.proposal_spec import ProposalSpec, rule_spec
from darwin.mysterio.safety import MutationKind
from darwin.self_modification import ProposedModification


@dataclass
class MetaProposerContext:
    """The slice of runtime the meta-proposer reads to generate proposals."""

    darwin: Any
    runtime: Any
    recent_outcomes: list[Any]
    last_simulation: dict[str, Any] | None
    last_uncertainty_scan: dict[str, Any] | None


class ProposalStrategy(Protocol):
    name: str

    def __call__(self, ctx: MetaProposerContext) -> list[ProposedModification]:
        ...


class MetaProposer:
    """Plug-in registry of proposal-generation strategies."""

    def __init__(self) -> None:
        self._strategies: dict[str, ProposalStrategy] = {}
        self._seen_signatures: set[str] = set()
        self._register_defaults()

    def register(self, name: str, strategy: Callable[[MetaProposerContext], list[ProposedModification]]) -> None:
        strategy.__name__ = name  # type: ignore[attr-defined]
        strategy.name = name  # type: ignore[attr-defined]
        self._strategies[name] = strategy  # type: ignore[assignment]

    def strategies(self) -> list[str]:
        return list(self._strategies)

    def propose(self, ctx: MetaProposerContext) -> list[ProposedModification]:
        proposals: list[ProposedModification] = []
        for strategy in self._strategies.values():
            try:
                emitted = strategy(ctx)
            except Exception:  # defensive — a bad strategy must not kill the cycle
                continue
            for proposal in emitted:
                spec = getattr(proposal, "spec", None)
                if spec is not None:
                    sig = spec.introspection_signature
                    if sig in self._seen_signatures:
                        continue
                    self._seen_signatures.add(sig)
                proposals.append(proposal)
        return proposals

    def _register_defaults(self) -> None:
        self.register("variable_driven", _strategy_variable_driven)
        self.register("hypothesis_driven", _strategy_hypothesis_driven)
        self.register("loop_starvation", _strategy_loop_starvation)
        self.register("consolidation", _strategy_consolidation)
        self.register("gate_evolution", _strategy_gate_evolution)


